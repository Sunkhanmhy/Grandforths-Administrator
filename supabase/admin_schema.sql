create policy "Admins can read their own profile"
on public.admin_profiles for select
using (auth.uid() = auth_user_id);

create policy "Admins can update their own profile"
on public.admin_profiles for update
using (auth.uid() = auth_user_id)
with check (auth.uid() = auth_user_id);

create policy "Admins can read role metadata"
on public.admin_roles for select
using (auth.uid() is not null);

create policy "Admins can read permission metadata"
on public.admin_permissions for select
using (auth.uid() is not null);

create policy "Admins can read assigned roles"
on public.admin_user_roles for select
using (
  exists (
    select 1 from public.admin_profiles ap
    where ap.id = admin_user_roles.profile_id and ap.auth_user_id = auth.uid()
  )
);

create policy "Super admins can invite other admins"
on public.admin_invitations for insert
with check (
  exists (
    select 1
    from public.admin_profiles ap
    join public.admin_user_roles aur on aur.profile_id = ap.id
    where ap.auth_user_id = auth.uid() and aur.role_name = 'super_admin'
  )
);

create policy "Admins can read invitations for their own profile"
on public.admin_invitations for select
using (
  exists (
    select 1 from public.admin_profiles ap
    where ap.email = admin_invitations.email and ap.auth_user_id = auth.uid()
  )
  or exists (
    select 1
    from public.admin_profiles ap
    join public.admin_user_roles aur on aur.profile_id = ap.id
    where ap.auth_user_id = auth.uid() and aur.role_name = 'super_admin'
  )
);

create policy "Authenticated admins can write audit records"
on public.audit_logs for insert
with check (
  auth.uid() is not null
);

create policy "Admins can read own audit records"
on public.audit_logs for select
using (
  profile_id in (
    select id from public.admin_profiles where auth_user_id = auth.uid()
  )
  or exists (
    select 1
    from public.admin_profiles ap
    join public.admin_user_roles aur on aur.profile_id = ap.id
    where ap.auth_user_id = auth.uid() and aur.role_name = 'super_admin'
  )
);

create index if not exists idx_admin_profiles_auth_user_id on public.admin_profiles(auth_user_id);
