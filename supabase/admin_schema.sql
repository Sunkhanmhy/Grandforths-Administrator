create or replace function public.current_admin_profile_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id
  from public.admin_profiles
  where auth_user_id = auth.uid()
  limit 1;
$$;

create or replace function public.handle_new_admin_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.admin_profiles (auth_user_id, email, full_name, status)
  values (
    new.id,
    lower(new.email),
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    'active'
  )
  on conflict (auth_user_id) do nothing;

  insert into public.admin_user_roles (profile_id, role_name)
  select id, 'super_admin'
  from public.admin_profiles
  where auth_user_id = new.id
  on conflict (profile_id, role_name) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_admin_created on auth.users;
create trigger on_auth_admin_created
after insert on auth.users
for each row execute function public.handle_new_admin_user();

