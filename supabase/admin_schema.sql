create extension if not exists pgcrypto;

create table if not exists public.admin_profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique,
  email text not null unique,
  full_name text not null,
  status text not null default 'active' check (status in ('active', 'disabled', 'pending')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_roles (
  name text primary key,
  label text not null,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_permissions (
  key text primary key,
  description text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_role_permissions (
  role_name text not null references public.admin_roles(name) on delete cascade,
  permission_key text not null references public.admin_permissions(key) on delete cascade,
  primary key (role_name, permission_key)
);

create table if not exists public.admin_user_roles (
  profile_id bigint not null references public.admin_profiles(id) on delete cascade,
  role_name text not null references public.admin_roles(name) on delete cascade,
  primary key (profile_id, role_name)
);

create table if not exists public.admin_invitations (
  id bigint generated by default as identity primary key,
  email text not null unique,
  invited_by bigint references public.admin_profiles(id) on delete set null,
  role_name text not null references public.admin_roles(name),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'expired', 'revoked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  profile_id bigint references public.admin_profiles(id) on delete set null,
  action text not null,
  entity text not null,
  details jsonb,
  created_at timestamptz not null default now()
);

